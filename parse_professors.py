def map_department(courses):
    c = courses.lower()
    if any(x in c for x in ['كيميائي', 'بترول', 'مادة', 'تفاعلات']):
        return 'chemical'
    if any(x in c for x in ['انشائي', 'خرسانة', 'مساحة', 'مرور', 'طرق', 'مباني']):
        return 'civil'
    if any(x in c for x in ['ميكانيكي', 'حرارية', 'موائع', 'اهتزازات', 'تصنيع', 'مواد']):
        return 'mechanical'
    if any(x in c for x in ['مركبات', 'سيارات', 'اوتوترونيكس', 'تكييف']):
        return 'autotronics'
    if any(x in c for x in ['ميكاترونكس', 'تحكم', 'آلي']):
        return 'mechatronics'
    if any(x in c for x in ['كهربائي', 'آلات', 'قوى', 'كهرومغناطيسية']):
        return 'electrical'
    if any(x in c for x in ['اتصالات', 'اشارات', 'امواج', 'رقمية']):
        return 'telecom'
    if any(x in c for x in ['سيبراني', 'تشفير', 'أمن']):
        return 'network-security'
    if any(x in c for x in ['حاسوب', 'بيانات', 'برمجة', 'ذكاء', 'خوارزميات']):
        return 'computer'
    if any(x in c for x in ['تفاضل', 'فيزياء', 'كيمياء', 'جبر', 'إحصاء', 'رياضيات', 'معادلات']):
        return 'basic-sciences'
    if any(x in c for x in ['اسلام', 'لغة', 'عسكرية', 'وطنية', 'سلامة', 'خلفاء']):
        return 'general-requirements'
    if 'اقتصاد' in c:
        return 'industrial'
    return 'general'

